const { test, expect } = require('../e2e-fixtures.cjs');
const { settingsCategory } = require('../e2e-settings-helpers.cjs');
for(const width of [320,390,1280]) test(`settings hub exposes all categories and keeps drafts at ${width}`,async({page},info)=>{
 await page.setViewportSize({width,height:844});
 await page.goto('/room/settings');
 const cards=page.locator('.settings-category-card');
 await expect(cards).toHaveCount(8);
 if(width===390) for(const card of await cards.all()) await expect(card).toBeInViewport();
 await expect(page.locator('.settings-savebar')).toHaveCount(0);
 await expect(page.locator('.site-music-drawer')).not.toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath('settings-hub.png')});
 await settingsCategory(page,'角色与对话');
 const panel=page.getByTestId('room-dialogue-settings');
 await expect(panel.getByLabel('启用卡片世界书',{exact:false})).toBeVisible();
 await panel.getByLabel('希望八千代怎样认识你',{exact:true}).fill('草稿保留测试');
 await settingsCategory(page,'长期记忆');
 await settingsCategory(page,'角色与对话');
 await expect(panel.getByLabel('希望八千代怎样认识你',{exact:true})).toHaveValue('草稿保留测试');
 await page.getByRole('searchbox',{name:'搜索设置',exact:true}).fill('世界书');
 await page.locator('.settings-results').getByRole('button',{name:/角色卡与世界书/}).click();
 await expect(panel).toBeInViewport();
 await page.locator('.settings-page-heading').getByRole('link',{name:'返回房间'}).click();
 const leave=page.getByRole('dialog',{name:'保存修改后离开？'});
 await expect(leave).toBeVisible();
 await leave.getByRole('button',{name:'继续编辑'}).click();
 await expect(panel.getByLabel('希望八千代怎样认识你',{exact:true})).toHaveValue('草稿保留测试');
 await page.locator('.settings-savebar').getByRole('button',{name:'保存修改'}).click();
 await expect(page.locator('.settings-save-state')).toContainText('已保存');
 await page.reload();
 await settingsCategory(page,'角色与对话');
 await expect(panel.getByLabel('希望八千代怎样认识你',{exact:true})).toHaveValue('草稿保留测试');
});
