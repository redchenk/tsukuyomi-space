export function arrivalPose(seconds){
  const sample=Math.max(0,Math.min(controls.length-3,seconds/interval));
  const i=Math.min(controls.length-4,Math.floor(sample)),u=sample-i;
  const u2=u*u,u3=u2*u;
  const w=[(1-u)**3, 3*u3-6*u2+4, -3*u3+3*u2+3*u+1, u3];
  return controls[i].map((_,c)=>(
    w[0]*controls[i][c]+w[1]*controls[i+1][c]+w[2]*controls[i+2][c]+w[3]*controls[i+3][c]
  )/6);
}
